function detectLang() {
  if (typeof window === 'undefined') return 'zh';
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'zh' || stored === 'en') return stored;
  } catch (error) {
    // storage may be unavailable in private contexts
  }
  return 'zh';
}

let currentLang = detectLang();
const listeners = new Set();

export function getLang() {
  return currentLang;
}

export function isZh() {
  return currentLang === 'zh';
}

export function setLang(code) {
  if (code !== 'zh' && code !== 'en') return;
  if (code === currentLang) return;
  currentLang = code;
  try {
    window.localStorage.setItem(STORAGE_KEY, code);
  } catch (error) {
    // ignore storage failures
  }
  applyDocumentLang();
  for (const listener of Array.from(listeners)) {
    try {
      listener(code);
    } catch (error) {
      // a failing listener must not block the others
    }
  }
}

export function onLangChange(listener) {
  listeners.add(listener);
  return function unsubscribe() {
    listeners.delete(listener);
  };
}

export function applyDocumentLang() {
  if (typeof document === 'undefined') return;
  const meta = LANGUAGES.find((item) => item.code === currentLang) || LANGUAGES[0];
  document.documentElement.lang = meta.htmlLang;
  document.documentElement.setAttribute('data-lang', currentLang);
  document.title = currentLang === 'zh'
    ? '厚土 · ThickEarth'
    : 'ThickEarth · 厚土';
}

function interpolate(template, vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const value = vars[key];
    return value === null || value === undefined ? match : String(value);
  });
}

export function t(key, vars) {
  const table = DICT[currentLang] || DICT.zh;
  let value = table[key];
  if (value === undefined && currentLang !== 'en') value = DICT.en[key];
  if (value === undefined) return key;
  return interpolate(value, vars);
}

export function hasKey(key) {
  const table = DICT[currentLang] || DICT.zh;
  return Object.prototype.hasOwnProperty.call(table, key);
}

/**
 * Pick the first present numeric/scalar value from a summary payload using
 * known aliases, so the UI keeps working if the server adds or renames fields.
 */
export function pickValue(source, keys) {
  if (!source || typeof source !== 'object') return undefined;
  for (const key of keys) {
    const value = source[key];
    if (value !== undefined && value !== null) return value;
  }
  return undefined;
}
